-- TEST 2: SALES AND CUSTOMER RELATIONSHIP VALIDATION ---> Verify that every sale is linked to an existing customer.
SELECT COUNT(*) AS INVALID_CUSTOMER_REFERENCES
FROM SALES S LEFT JOIN CUSTOMER C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;


-- TEST 3: SALES ITEMS AND SALES RELATIONSHIP VALIDATION -----> Verify that every sales item is linked to an existing sales order. 
SELECT COUNT(*) AS INVALID_SALES_REFERENCES
FROM SALES_ITEMS SI LEFT JOIN SALES S
    ON SI.SALES_ID = S.SALES_ID
WHERE S.SALES_ID IS NULL;


-- TEST 4: SALES ITEMS AND PRODUCT RELATIONSHIP VALIDATION ------> Verify that every sales item is linked to an existing product.
SELECT COUNT(*) AS INVALID_PRODUCT_REFERENCES
FROM SALES_ITEMS SI LEFT JOIN PRODUCT P
    ON SI.PRODUCT_ID = P.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL;


-- TEST 5: PRODUCT AND CATEGORY RELATIONSHIP VALIDATION ------> Verify that every product is linked to an existing category.
SELECT COUNT(*) AS INVALID_CATEGORY_REFERENCES
FROM PRODUCT P LEFT JOIN CATEGORY C
    ON P.CATEGORY_ID = C.CATEGORY_ID
WHERE C.CATEGORY_ID IS NULL;


-- TEST 6: CUSTOMER AND REGION RELATIONSHIP VALIDATION -------> Verify that every customer is linked to an existing region.
SELECT COUNT(*) AS INVALID_REGION_REFERENCES
FROM CUSTOMER C LEFT JOIN REGION R
    ON C.REGION_ID = R.REGION_ID
WHERE R.REGION_ID IS NULL;


-- TEST 7: PRODUCT PRICE AND STOCK VALIDATION -----> Verify that no product has a zero, negative, or missing price or stock quantity.
SELECT COUNT(*) AS INVALID_PRODUCT_RECORDS
FROM PRODUCT
WHERE UNIT_PRICE IS NULL OR UNIT_PRICE <= 0 OR STOCK_QUANTITY IS NULL OR STOCK_QUANTITY <= 0;


-- TEST 8: SALES ITEM QUANTITY AND DISCOUNT VALIDATION -------> Verify that all sales items have positive quantities and discounts between 0% and 100%.
SELECT COUNT(*) AS INVALID_SALES_ITEM_RECORDS
FROM SALES_ITEMS
WHERE QUANTITY IS NULL OR QUANTITY <= 0 OR DISCOUNT_PERCENT < 0 OR DISCOUNT_PERCENT > 100;


-- TEST 9: SALES ITEM PRICE CONSISTENCY VALIDATION ------> Verify that every sales item has the same unit price as its corresponding product.
SELECT COUNT(*) AS INVALID_PRICE_RECORDS
FROM SALES_ITEMS SI INNER JOIN PRODUCT P
    ON SI.PRODUCT_ID = P.PRODUCT_ID
WHERE SI.UNIT_PRICE <> P.UNIT_PRICE OR SI.UNIT_PRICE IS NULL;


