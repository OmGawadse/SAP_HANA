-- Verify data consistency between CUSTOMER and SALES tables. Check whether any customer made a purchase before their registration date.
SELECT COUNT(*) AS INVALID_DATE_RECORDS
FROM SALES S INNER JOIN CUSTOMER C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
WHERE S.PURCHASE_DATE < C.REG_DATE;


