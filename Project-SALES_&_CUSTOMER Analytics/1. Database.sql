CREATE COLUMN TABLE CUSTOMER ( 
    CUSTOMER_ID INT PRIMARY KEY, 
    NAME NVARCHAR(100) NOT NULL, 
    CITY NVARCHAR(50), 
    EMAIL NVARCHAR(100) UNIQUE, 
    PHN_NO NVARCHAR(15), 
    REG_DATE DATE NOT NULL,
	CONSTRAINT CHK_PHN_NO 
	CHECK (PHN_NO IS NULL OR PHN_NO LIKE_REGEXPR '^[0-9]+$'));
SELECT * FROM CUSTOMER;


CREATE COLUMN TABLE REGION (
	REGION_ID INT PRIMARY KEY,
	REGION_NAME NVARCHAR(50) NOT NULL,
	COUNTRY NVARCHAR(50) NOT NULL);
SELECT * FROM REGION;


CREATE COLUMN TABLE PRODUCT (
	PRODUCT_ID INT PRIMARY KEY,
	PRODUCT_NAME NVARCHAR(100) NOT NULL,
	CATEGORY_ID INT,
	UNIT_PRICE DECIMAL(10, 2) NOT NULL,
	STOCK_QUANTITY INT NOT NULL);
SELECT * FROM PRODUCT;


CREATE COLUMN TABLE CATEGORY ( 
    CATEGORY_ID INT PRIMARY KEY, 
    CATEGORY_NAME NVARCHAR(100) NOT NULL, 
    DESCRIPTION NVARCHAR(255));
SELECT * FROM CATEGORY;


CREATE COLUMN TABLE SALES (
    SALES_ID INT PRIMARY KEY,
    CUSTOMER_ID INT NOT NULL,
    PURCHASE_DATE DATE NOT NULL,
    PAYMENT_METHOD NVARCHAR(30),
    ORDER_STATUS NVARCHAR(30));
SELECT * FROM SALES;


CREATE COLUMN TABLE SALES_ITEMS(
    SALES_ITEM_ID INT PRIMARY KEY,
    SALES_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE DECIMAL(10,2) NOT NULL,
    DISCOUNT_PERCENT DECIMAL(5,2));
SELECT * FROM SALES_ITEMS;

-- A Foreign Key (FK) creates a relationship between two tables by referencing the Primary Key (PK) of another table.
-- Relationship 1 – CUSTOMER → REGION
ALTER TABLE CUSTOMER ADD (REGION_ID INT);
ALTER TABLE CUSTOMER
ADD CONSTRAINT FK_CUSTOMER_REGION FOREIGN KEY (REGION_ID)
REFERENCES REGION (REGION_ID);

-- Relationship 2 – PRODUCT → CATEGORY
ALTER TABLE PRODUCT
ADD CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID)
REFERENCES CATEGORY (CATEGORY_ID);

-- Relationship 3 – SALES → CUSTOMER
ALTER TABLE SALES
ADD CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
REFERENCES CUSTOMER (CUSTOMER_ID);

-- Relationship 4 – SALES_ITEMS → SALES
ALTER TABLE SALES_ITEMS
ADD CONSTRAINT FK_ITEMS_SALES FOREIGN KEY (SALES_ID)
REFERENCES SALES (SALES_ID);

-- Relationship 5 – SALES_ITEMS → PRODUCT
ALTER TABLE SALES_ITEMS
ADD CONSTRAINT FK_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID)
REFERENCES PRODUCT (PRODUCT_ID);

