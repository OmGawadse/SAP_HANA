-- TASK 1: TOTAL SALES REVENUE ------> Calculate total revenue after applying discounts to all sales items.

SELECT
    ROUND (
        SUM(QUANTITY * UNIT_PRICE * (1 - DISCOUNT_PERCENT / 100)), 2         -- QUANTITY * UNIT_PRICE calculates the original amount, (1 - DISCOUNT_PERCENT / 100) applies the discount.
    ) AS TOTAL_REVENUE
FROM SALES_ITEMS;   -- ₹3.50 crore approximately


-- TASK 2: MONTHLY SALES ANALYSIS ------> Calculate total revenue generated in each month after applying discounts.

SELECT
    YEAR(S.PURCHASE_DATE) AS SALES_YEAR, MONTH(S.PURCHASE_DATE) AS SALES_MONTH,           -- YEAR() & MONTH() extract the purchase year and month.
    ROUND (
    SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0)/100)), 2)   -- -- COALESCE()- If DISCOUNT_PERCENT is NULL, it replaces it with 0, meaning no discount.
    AS MONTHLY_REVENUE -- COALESCE(20, 0) = 20,     20 / 100 = 0.20,    1 - 0.20 = 0.80
FROM SALES S INNER JOIN SALES_ITEMS SI
    ON S.SALES_ID = SI.SALES_ID
GROUP BY YEAR(S.PURCHASE_DATE), MONTH(S.PURCHASE_DATE)
ORDER BY SALES_YEAR, SALES_MONTH;


-- TASK 3: CITY-WISE SALES ANALYSIS -------> Calculate total revenue generated by customers from each city.

SELECT C.CITY, ROUND (SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS CITY_REVENUE
FROM CUSTOMER C INNER JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
INNER JOIN SALES_ITEMS SI
    ON S.SALES_ID = SI.SALES_ID
GROUP BY C.CITY
ORDER BY CITY_REVENUE DESC;


-- TASK 4: REGION-WISE SALES ANALYSIS -----> Calculate total revenue generated by customers from each region.

SELECT R.REGION_NAME, ROUND(SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS REGION_REVENUE
FROM REGION R INNER JOIN CUSTOMER C         -- CUSTOMER acts as the bridge between REGION and SALES.
    ON R.REGION_ID = C.REGION_ID
INNER JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
INNER JOIN SALES_ITEMS SI
    ON S.SALES_ID = SI.SALES_ID
GROUP BY R.REGION_NAME
ORDER BY REGION_REVENUE DESC;


-- TASK 5: TOP 10 CUSTOMERS BY REVENUE ------> Identify the ten customers who generated the highest total sales revenue.

SELECT TOP 10
    C.CUSTOMER_ID, C.NAME AS CUSTOMER_NAME, C.CITY,
    ROUND(SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS TOTAL_SPENT
FROM CUSTOMER C INNER JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
INNER JOIN SALES_ITEMS SI
    ON S.SALES_ID = SI.SALES_ID
GROUP BY C.CUSTOMER_ID, C.NAME, C.CITY
ORDER BY TOTAL_SPENT DESC;


-- TASK 6: CATEGORY-WISE SALES ANALYSIS -------> Calculate total revenue generated by products in each category.

SELECT C.CATEGORY_NAME, ROUND(SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS CATEGORY_REVENUE
FROM CATEGORY C INNER JOIN PRODUCT P
    ON C.CATEGORY_ID = P.CATEGORY_ID
INNER JOIN SALES_ITEMS SI
    ON P.PRODUCT_ID = SI.PRODUCT_ID
GROUP BY C.CATEGORY_NAME
ORDER BY CATEGORY_REVENUE DESC;


-- TASK 7: TOP-SELLING PRODUCTS -------> Identify the ten products with the highest quantity sold and their revenue.

SELECT TOP 10
    P.PRODUCT_ID, P.PRODUCT_NAME, SUM(SI.QUANTITY) AS TOTAL_QUANTITY_SOLD,          -- calculates the total units sold for each product.
    ROUND(SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS PRODUCT_REVENUE
FROM PRODUCT P INNER JOIN SALES_ITEMS SI
    ON P.PRODUCT_ID = SI.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;


-- TASK 8: AVERAGE ORDER VALUE
-- Calculate the average amount customers spend per sales transaction after discounts.

SELECT ROUND( SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)) 
        / COUNT(DISTINCT S.SALES_ID),           -- counts each sales transaction only once.
        2) AS AVERAGE_ORDER_VALUE
FROM SALES S INNER JOIN SALES_ITEMS SI
ON S.SALES_ID = SI.SALES_ID;


-- TASK 9: YEAR-WISE SALES REVENUE PROCEDURE
-- Create a reusable procedure to calculate revenue for a specified year.

CREATE PROCEDURE GET_YEARLY_REVENUE ( IN P_YEAR INT )
LANGUAGE SQLSCRIPT AS
BEGIN

    SELECT YEAR(S.PURCHASE_DATE) AS SALES_YEAR,
        ROUND(SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)), 2) AS TOTAL_REVENUE
    FROM SALES S INNER JOIN SALES_ITEMS SI
        ON S.SALES_ID = SI.SALES_ID
    WHERE YEAR(S.PURCHASE_DATE) = :P_YEAR
    GROUP BY YEAR(S.PURCHASE_DATE);

END;
