-- TASK 10: TOTAL REVENUE CONSISTENCY VERIFICATION
-- Verify that the sum of monthly revenue matches the overall sales revenue.

WITH MONTHLY_SALES AS (             --- We create a temporary named result called MONTHLY_SALES t-t--This process is called a Common Table Expression (CTE).
    SELECT YEAR(S.PURCHASE_DATE) AS SALES_YEAR, MONTH(S.PURCHASE_DATE) AS SALES_MONTH,
        SUM(SI.QUANTITY * SI.UNIT_PRICE * (1 - COALESCE(SI.DISCOUNT_PERCENT, 0) / 100)) AS MONTHLY_REVENUE
    FROM SALES S INNER JOIN SALES_ITEMS SI
        ON S.SALES_ID = SI.SALES_ID
    GROUP BY YEAR(S.PURCHASE_DATE), MONTH(S.PURCHASE_DATE)
)
SELECT ROUND(SUM(MONTHLY_REVENUE), 2) AS VERIFIED_TOTAL_REVENUE  -- reads the result produced by our CTE. Combine monthly results into one total
FROM MONTHLY_SALES;














