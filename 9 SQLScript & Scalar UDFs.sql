-- security settings
-- INVOKER = the person who calls the function. DEFINER = the person who creates the function.
-- INVOKER uses the caller's privileges, whereas DEFINER uses the function creator's privileges

-- Create a function to calculate a 10% discount -> Runtime-created function vs. design-time development object
-- Runtime-created function - created directly in the database using SQL statements
-- Design-time functions are developed using package within a project and then deployed or activated in the database.

-- Here Simply runtime function is used.

CREATE FUNCTION FUNC_DISCOUNT (price DECIMAL(10,2)) RETURNS DISCOUNT DECIMAL(10,2)
LANGUAGE SQLScript 
SQL SECURITY INVOKER AS 
BEGIN 
    DISCOUNT := :price * 0.10; 
END;

CREATE FUNCTION FUNC_DIS_amt (price DECIMAL(10,2)) RETURNS amount DECIMAL(10,2)
LANGUAGE SQLScript 
SQL SECURITY INVOKER AS 
BEGIN 
    amount := :price - (:price* 0.10); 
END;

SELECT *, "PRACTICE_33"."FUNC_DISCOUNT"("MRP") AS "DISCOUNT", "PRACTICE_33"."FUNC_DIS_AMT"("MRP") AS "Final_Amount"             -- Just Pass the Parameters & it's Job Doneeeee.
