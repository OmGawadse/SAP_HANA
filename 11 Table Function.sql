--********************************************* DYNAMIC FILTER TABLE FUNCTION ***************************************

CREATE FUNCTION FUNC_BOOK(DF VARCHAR(1000)) RETURNS TABLE (BOOK_ID VARCHAR(5), CATEGORY VARCHAR(10), MRP DECIMAL(10,2),          FINAL_AMT DECIMAL(10,2))
LANGUAGE SQLSCRIPT 
SQL SECURITY INVOKER AS
BEGIN 
X = APPLY_FILTER ("T4H"."Books", :DF);
RETURN
SELECT BOOK_ID, CATEGORY, MRP, "PRACTICE_33"."FINAL_PRICE"(MRP, 10) AS FINAL_AMT FROM :X;

END;

