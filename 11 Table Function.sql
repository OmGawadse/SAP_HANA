--**************************************************************************Combining Scalar UDFs and Table UDFs ************************************************************************
CREATE FUNCTION FUNC_BOOK(CAT VARCHAR(15)) RETURNS TABLE (BOOK_ID VARCHAR(5), CATEGORY VARCHAR(10), MRP DECIMAL(10,2),          FINAL_AMT DECIMAL(10,2))
LANGUAGE SQLSCRIPT 
SQL SECURITY INVOKER AS
BEGIN 
RETURN
SELECT BOOK_ID, CATEGORY, MRP, "PRACTICE_33"."FINAL_PRICE"(MRP, 10) AS FINAL_AMT FROM "T4H"."Books" WHERE CATEGORY = :CAT;

END;

DROP FUNCTION FUNC_BOOK
