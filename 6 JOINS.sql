-- IDENTITY - Automatically generates a numeric value for a column when you insert a new row........
 
CREATE COLUMN TABLE "PK_SALES"
(
    "ORDER_NO" INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "PRODUCT" NVARCHAR(10),
    "QTY" INTEGER DEFAULT 1 NOT NULL, -- If you don't provide a quantity while inserting, HANA automatically uses 1.
    "ORDER_DATE" DATE DEFAULT CURRENT_DATE,
    PRIMARY KEY INVERTED VALUE ("ORDER_NO", "PRODUCT")
)
UNLOAD PRIORITY 5       -- Unload priority determines how likely a table is to be unloaded from memory when memory is needed. like from RAM
AUTO MERGE;             -- Auto merge automatically merges delta storage(Modified one) into main storage in column tables, helping maintain query performance.
                        -- Unload priority = memory management. Auto merge = storage management.

